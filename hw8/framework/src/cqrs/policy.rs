/// Политика (process manager): реагирует на события новыми командами.
///
/// Это чистая функция: что делать, решает политика, а выполнит ли команду система —
/// агрегат. Поэтому отклонённая команда политики — нормальный исход, а не сбой.
/// Запускается через [`run_policy`](super::runner::run_policy).
pub trait Policy<E> {
    type Command;

    fn react(&self, event: &E) -> Vec<Self::Command>;
}
